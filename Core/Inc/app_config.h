/* ============================================================
 * app_config.h —— 应用层配置总开关
 *
 * 编译期的几个开关集中在这里，方便做对照实验。
 * 每个开关都对应执行计划里的一项验收动作。
 * ============================================================ */
#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/* ============================================================
 * ① 互斥锁总开关
 *
 *   1 = 正常（默认）：log_begin/end 与总线访问都受互斥锁保护
 *   0 = 关锁：log_begin/end 变成空操作
 *
 * ★ W3 D4 的对照实验就是用这个开关做的：
 *     改成 0 → 编译烧录 → 观察串口输出错乱（两行文字互相插队）
 *     改回 1 → 编译烧录 → 恢复正常
 *   这个前后对比是面试讲到"为什么需要互斥锁"时最有说服力的素材，
 *   因为它是你【亲眼看见】的，不是背下来的。
 * ============================================================ */
#ifndef APP_MUTEX_ENABLE
#define APP_MUTEX_ENABLE        1
#endif

/* ============================================================
 * ② 栈尺寸来源
 *
 *   0 = 用"宽裕"值先跑起来（默认，第一次必须用这个）
 *   1 = 用实测水位 × 1.5 重新分配后的值
 *
 * ★ 正确顺序不能颠倒：
 *     先用 0 跑 → 读 uxTaskGetStackHighWaterMark 打印的剩余水位
 *     → 峰值 = 分配值 − 剩余值 → 新分配 = 峰值 × 1.5
 *     → 把新值填进下面的"实测档"→ 改成 1 重新编译
 *   【绝对不能】先猜一个小数字然后祈祷它不溢出。
 * ============================================================ */
#ifndef APP_STACK_MEASURED
#define APP_STACK_MEASURED      0
#endif

/* ============================================================
 * ③ 串口详略
 *
 *   1 = 每采一条就打印一行（做互斥锁对照实验时必须用这个）
 *   0 = 每 60 条打印一行（跑 24 小时稳定性测试时用这个，
 *       否则一天 17 万行日志，终端会卡死）
 * ============================================================ */
#ifndef APP_UART_VERBOSE
#define APP_UART_VERBOSE        1
#endif

/* ============================================================
 * ④ 开机是否自动跑 W4 自检
 *
 *   1 = 开机自动跑一次（会往 Flash 写测试数据，建议只在联调期开）
 *   0 = 不跑，需要时用串口命令 t 手动触发（默认）
 * ============================================================ */
#ifndef APP_SELFTEST_ON_BOOT
#define APP_SELFTEST_ON_BOOT    0
#endif

/* ============================================================
 * ⑤ 温度/湿度的记录量化单位换算系数
 *
 * BME280 驱动输出的是 0.01 ℃ / 0.01 %RH，
 * 而记录格式定的是 ℃×1000 / %RH×1000（分辨率 0.001）。
 * 所以写记录时要 ×10。
 * 把这个系数单列出来，是为了将来换更高精度的传感器时只改一处。
 * ============================================================ */
#define APP_TEMP_SCALE      10UL
#define APP_HUMI_SCALE      10UL

#endif /* APP_CONFIG_H */
