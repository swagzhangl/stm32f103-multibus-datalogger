/* ============================================================
 * app_tasks.h —— 应用层三任务架构
 *
 * ============================================================
 *  任务划分
 * ============================================================
 *   任务      优先级  周期/触发        职责                   用到的 IPC
 *   --------  ------  --------------  --------------------  ----------------
 *   acq        4      1 s（不漂移）    读 BME280 → 队列       互斥锁（I2C）
 *   proc       3      队列唤醒         报警判定 + 打包落库     互斥锁（SPI）
 *                                                            二值信号量（报警事件）
 *   comm       2      20 ms 轮询       串口上报 + 命令处理      互斥锁（UART/I2C/SPI）
 *
 * ------------------------------------------------------------
 * 【为什么是这三个任务，而不是一个超级循环】
 *
 *   ① 采集和存储的"速度"天生不同。
 *      采集任务必须严格 1 s 一次（简历上写的"周期不漂移"就是这个）；
 *      而写 Flash 一次要 1~2 ms，偶尔还要擦扇区（45 ms 典型、400 ms 最坏）。
 *      如果放在同一个循环里，擦扇区那一下就会把采集周期顶掉。
 *      ⇒ 用【消息队列】把两者解耦：采集只管往队列里放，
 *        队列缓冲了这种速度差。这就是队列存在的意义。
 *
 *   ② 报警是"事件"，不是"数据"。
 *      队列适合传数据（有缓冲、有长度）；信号量适合传事件（只关心"发生了"）。
 *      报警从"关"变"开"这一刻需要通知通信任务去记录，
 *      这就是【二值信号量】的典型用法。
 *      把队列和信号量用混，是新手最常见的 IPC 设计错误。
 *
 *   ③ 三条总线是共享资源，必须互斥。
 *      I2C 被采集任务和命令处理同时用；
 *      SPI 被处理任务（写记录）和命令处理（回读记录）同时用；
 *      UART 被三个任务同时用。
 *      不加锁就会出现"一个任务的输出/事务中途被另一个任务插队"。
 * ============================================================ */
#ifndef APP_TASKS_H
#define APP_TASKS_H

#include <stdint.h>

/* ---------- 一个采样样本（队列里流动的数据）---------- */
typedef struct
{
    uint32_t seq;           /* 记录序号 */
    uint32_t timestamp_s;   /* 时间戳（秒）*/
    int32_t  temp_centi;    /* 温度 0.01 ℃ */
    uint32_t humi_centi;    /* 湿度 0.01 %RH */
    uint32_t press_pa;      /* 气压 Pa */
    uint8_t  alarm;         /* 处理任务判定后的报警状态 */
    uint8_t  store_rc;      /* 落库返回码；0xFF = 未尝试 */
    uint8_t  used;          /* 1 = 本次采样有效（传感器读成功且通过合理性校验）*/
} app_sample_t;

/* 创建任务与 IPC 对象。必须由 main() 在启动调度器【之前】调用一次。
 * 返回 0 = 成功，非 0 = 某个 IPC 对象创建失败（内存不够）。 */
uint8_t app_tasks_start(void);

/* ---------- 共享总线互斥锁（自检 / 命令处理也要用）---------- */
/* 返回 1 = 拿到锁；0 = 超时（说明有别的任务长时间占着）*/
uint8_t app_lock_i2c(uint32_t timeout_ms);
void    app_unlock_i2c(void);
uint8_t app_lock_spi(uint32_t timeout_ms);
void    app_unlock_spi(void);

/* ---------- 诊断 ---------- */
uint32_t app_get_seconds(void);
uint32_t app_get_drop_raw(void);      /* 采集队列满丢弃数 */
uint32_t app_get_drop_rep(void);      /* 上报队列满丢弃数 */
uint32_t app_get_lock_timeouts(void); /* 取锁超时次数 */

#endif /* APP_TASKS_H */
