/* ============================================================
 * buzzer.h —— 有源蜂鸣器（PB0）+ 带回差的湿度报警判定
 * ============================================================ */
#ifndef BUZZER_H
#define BUZZER_H

#include <stdint.h>

void buzzer_init(void);
void buzzer_on(void);
void buzzer_off(void);

/* ============================================================
 * 带回差的阈值报警判定（滞回 / hysteresis）
 *
 * 【为什么必须有回差】
 *   如果只有"湿度 > 65% 就响、≤ 65% 就停"这一条线，
 *   当湿度正好在 65% 附近波动（BME280 湿度精度是 ±3 %RH）时，
 *   蜂鸣器会以采样频率疯狂开合 —— 听起来像"哒哒哒"的杂音，
 *   而且继电器/蜂鸣器这种机电件这样抖会缩短寿命。
 *
 * 【回差怎么工作】
 *     湿度 > 65%          → 报警置位（进入报警态）
 *     湿度 < 62%          → 报警复位（退出报警态）
 *     62% ≤ 湿度 ≤ 65%    → 【保持原状态】
 *   那 3% 的死区就是"回差"。进去要越过 65，出来要跌破 62，
 *   中间来回晃不影响状态。两个阈值之差就是回差带。
 *
 * @param humi_centi  湿度，单位 0.01 %RH（6500 = 65.00 %RH）
 * @param state       指向报警状态的指针（由调用方持有，函数内更新）。
 *                    ★ 声明为 volatile：这个变量由处理任务写、
 *                      同时会被通信任务读（打印状态），编译器不能
 *                      把它优化进寄存器缓存。
 * @return 判定后的报警状态：1 = 报警中，0 = 正常
 * ============================================================ */
uint8_t buzzer_alarm_update(uint32_t humi_centi, volatile uint8_t *state);

#endif /* BUZZER_H */
