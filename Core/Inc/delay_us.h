/* ============================================================
 * delay_us.h —— 微秒级精确延时（DWT 周期计数器）
 *
 * 【为什么不用 for 空循环】
 *   空循环的延时长度取决于主频、优化等级、编译器版本，
 *   改了任何一项就失准。老版本 i2c_soft.c 里就是
 *   `for (volatile uint32_t i = 0; i < 5U; i++)`，注释里自己写着
 *   "HSI 8MHz 下约 3~4us" —— 一旦主频从 8 MHz 提到 72 MHz，
 *   这个延时会直接快 9 倍，I2C 就超速了，而且现象是
 *   "在 8 MHz 下好好的，一提频就不通"，非常难查。
 *
 * 【DWT 为什么准】
 *   Cortex-M3 内核自带一个周期计数器 DWT->CYCCNT，每个内核时钟 +1。
 *   72 MHz 下 1 µs = 72 个计数。这跟主频严格绑定，
 *   不需要"标定"，也无法被优化器优化掉。
 * ============================================================ */
#ifndef DELAY_US_H
#define DELAY_US_H

#include <stdint.h>

/* 必须在时钟树配好（SystemCoreClock 正确）之后调用一次 */
void delay_init(void);

void delay_us(uint32_t us);
void delay_ms(uint32_t ms);

/* 自检用：返回 1 = DWT 周期计数器可用；0 = 不可用（已退化为空循环延时）*/
uint8_t delay_is_dwt_ok(void);

/* ============================================================
 * 单调微秒计数（由 DWT 周期计数器换算）与【正确的】间隔计算
 *
 * 【为什么需要它】
 *   嵌入式里凡是"等待外部器件"的地方都必须带超时 ——
 *   "永不无限阻塞"是可靠性铁律。而判断超时需要一把时间尺子。
 *
 * ★★ delay_now_us() 的回绕周期【不是】2^32 微秒 ★★
 *   它返回的是 DWT->CYCCNT / 每微秒周期数，
 *   72 MHz 下 CYCCNT 每 2^32 个【周期】(约 59.65 秒)回绕一次，
 *   换算成微秒后是每 59652323 µs 回绕一次，不是 4294967296 µs。
 *
 *   所以 (now - t0) 这种"靠无符号减法跨回绕"的写法在这里【不成立】：
 *   跨过回绕点时会得到一个约 4.2e9 的巨大值，
 *   任何 timeout_us 判定都会立刻成立 → 【假超时】。
 *
 *   实测证据（2026-09-17 上板）：
 *     串口打出的 uart_hold_us=4235319666（真实值只有约 4700 µs），
 *     4235319666 = 2^32 - 59647630，正是跨回绕后的错误差值。
 *
 *   假超时的后果不是"多等一会儿"，而是：
 *     wait_busy() 立刻返回"仍忙" → 页编程被判失败 → 写指针不推进
 *     → 下一次采集往同一个已编程的槽位再写一次 → 按位与 → 半写记录。
 *   当天倒出的 3 条半写记录(idx 980/981/982)就是这么来的。
 *
 * ⇒ 判定间隔一律用 delay_elapsed_us()，不要自己写 (now - t0)。
 * ============================================================ */
uint32_t delay_now_us(void);

/* 回绕周期（微秒）。72 MHz 下约 59652323。DWT 不可用时返回 0。 */
uint32_t delay_us_period(void);

/* 从 t0 到现在过了多少微秒，【正确处理回绕】。
 * 要求真实间隔 < 回绕周期（本项目最大超时 1 s，远小于 59.65 s）。
 * DWT 不可用时返回 0 —— 调用方需自行退化成"按循环次数"计时。 */
uint32_t delay_elapsed_us(uint32_t t0);

#endif /* DELAY_US_H */
